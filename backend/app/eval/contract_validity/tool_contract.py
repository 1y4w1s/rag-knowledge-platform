TOOL_CASE_BY_ID: dict[str, ToolContractRecord] = {c.case_id: c for c in _TOOL_CASES}


def tool_contract_records() -> tuple[ToolContractRecord, ...]:
    return _TOOL_CASES


def tool_primary_counts() -> dict[str, int]:
    counts: dict[str, int] = {}
    for record in _TOOL_CASES:
        key = record.primary_contract_class.value
        counts[key] = counts.get(key, 0) + 1
    return counts
